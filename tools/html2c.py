#!/usr/bin/env python3
"""Turns web/index.html into source/webpage.h (the phone page the GameCube serves)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "web", "index.html"), encoding="utf-8").read()
out = ['/* Generated by tools/html2c.py from web/index.html - do not edit. */', '#pragma once', 'static const char WEBPAGE[] =']
for line in src.split("\n"):
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    out.append('    "%s\\n"' % esc)
out[-1] += ";"
open(os.path.join(here, "..", "source", "webpage.h"), "w").write("\n".join(out) + "\n")
print("webpage.h:", len(src.encode()), "bytes")
